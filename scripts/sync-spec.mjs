#!/usr/bin/env node
/**
 * Sync spec content from content/spec (git submodule) into content/docs/en/spec.
 *
 * - Chapter order comes from the "Document Map" table in the spec README.md
 *   (maintained in the spec repo); meta.json ends with "..." so unmapped
 *   chapters are appended automatically.
 * - README.md is emitted as index.md (fumadocs has no README handling).
 * - frontmatter `title` is injected from the first H1 when missing (required).
 * - Relative links to *.md are rewritten to site URLs; links into excluded
 *   content (e.g. changes/) point at GitHub instead.
 * - Raw HTML-ish tags outside code (e.g. `## set<T>`) are escaped so the
 *   markdown compiler does not silently drop them.
 *
 * Usage: node scripts/sync-spec.mjs [--quiet]
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SPEC_DIR = path.join(ROOT, 'content/spec');
const OUT_DIR = path.join(ROOT, 'content/docs/en/spec');
const LANG = 'en';
const SPEC_BASE = `${LANG}/docs/spec`;
const GITHUB_BLOB = 'https://github.com/xulo-lang/spec/blob/main/';
const BANNER =
  '<!-- Generated by scripts/sync-spec.mjs from content/spec. Do not edit this file directly. -->';
const ROOT_INDEX_DESCRIPTION =
  'The formal specification of the XULO programming language.';
const QUIET = process.argv.includes('--quiet');

const log = (...a) => console.log('[spec:sync]', ...a);
const warn = (...a) => console.warn('[spec:sync] WARN:', ...a);

function die(msg) {
  console.error('[spec:sync] ERROR:', msg);
  process.exit(1);
}

async function main() {
  let entries;
  try {
    const stat = await fs.stat(SPEC_DIR);
    if (!stat.isDirectory()) throw new Error('not a directory');
    entries = await fs.readdir(SPEC_DIR);
  } catch {
    warn(
      `content/spec not found or not initialized — run: git submodule update --init content/spec`,
    );
    warn('skipping sync (leaving existing generated content in place)');
    return;
  }
  if (entries.length === 0) {
    warn('content/spec is empty — run: git submodule update --init content/spec');
    warn('skipping sync');
    return;
  }

  const files = (await walk(SPEC_DIR)).sort();
  if (files.length === 0) die('no .md files found in content/spec');

  const copySet = new Set(files);
  const readme = await fs.readFile(path.join(SPEC_DIR, 'README.md'), 'utf8').catch(() => '');
  const order = parseDocumentMap(readme);
  if (!order) warn('Document Map not found in README.md — sidebar falls back to "..." ordering');

  const outFiles = [];
  for (const rel of files) {
    const source = await fs.readFile(path.join(SPEC_DIR, rel), 'utf8');
    const isRootIndex = rel === 'README.md';

    let body = transform(source, rel, copySet);
    const title = extractTitle(body, rel);
    const description = isRootIndex ? ROOT_INDEX_DESCRIPTION : undefined;
    body = ensureFrontmatter(body, title, description);
    body = injectBanner(body);

    const outRel = toOutRel(rel);
    outFiles.push({ rel: outRel, body });
  }

  const meta = renderRootMeta(order, copySet);
  outFiles.push({ rel: 'meta.json', body: meta + '\n' });

  // Replace the output directory atomically-ish: write to temp, then swap.
  const tmpDir = OUT_DIR + '.tmp';
  await fs.rm(tmpDir, { recursive: true, force: true });
  await fs.mkdir(tmpDir, { recursive: true });
  for (const f of outFiles) {
    const dest = path.join(tmpDir, f.rel);
    await fs.mkdir(path.dirname(dest), { recursive: true });
    await fs.writeFile(dest, f.body, 'utf8');
  }
  await fs.rm(OUT_DIR, { recursive: true, force: true });
  await fs.rename(tmpDir, OUT_DIR);

  if (!QUIET)
    log(`synced ${outFiles.length - 1} files from content/spec -> content/docs/en/spec`);
}

/** Collect .md files (excluding changes/ and dotfiles), posix-style relative paths. */
async function walk(dir, base = '') {
  const out = [];
  for (const e of await fs.readdir(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.')) continue;
    const rel = base ? `${base}/${e.name}` : e.name;
    if (e.isDirectory()) {
      if (e.name === 'changes') continue; // OpenSpec workflow, not site content
      out.push(...(await walk(path.join(dir, e.name), rel)));
    } else if (e.name.endsWith('.md')) {
      out.push(rel);
    }
  }
  return out;
}

/**
 * Parse the "## 4. Document Map" table of the spec README into an ordered
 * list of chapter targets (e.g. "introduction.md", "types/README.md").
 */
function parseDocumentMap(readme) {
  const lines = readme.split('\n');
  const start = lines.findIndex((l) => /^##\s+4\.\s+Document Map/.test(l));
  if (start === -1) return null;
  const targets = [];
  for (let i = start + 1; i < lines.length; i++) {
    const l = lines[i];
    if (/^##\s/.test(l)) break;
    const m = l.match(/^\|\s*\[`?[^\]`]+`?\]\(([^)]+)\)/);
    if (m) targets.push(m[1]);
  }
  return targets.length ? targets : null;
}

/** Map an original spec path to its site URL (README/index collapse to the folder). */
function siteUrlFor(rel) {
  const parts = rel.replace(/\.md$/, '').split('/');
  const last = parts[parts.length - 1];
  if (last === 'README' || last === 'index') parts.pop();
  return '/' + [SPEC_BASE, ...parts].filter(Boolean).join('/');
}

/** Rewrite links + escape HTML-ish text outside code fences and inline code. */
function transform(content, fileRel, copySet) {
  const lines = content.split('\n');
  let fence = null;
  return lines
    .map((line) => {
      const m = line.match(/^(\s{0,3})(```+|~~~+)/);
      if (m) {
        const marker = m[2][0];
        if (fence === null) fence = marker;
        else if (fence === marker) fence = null;
        return line;
      }
      if (fence !== null) return line;
      return processOutsideCode(line, fileRel, copySet);
    })
    .join('\n');
}

function processOutsideCode(line, fileRel, copySet) {
  const ranges = codeSpanRanges(line);
  const rewritten = rewriteLinks(line, fileRel, copySet, ranges);
  const ranges2 = codeSpanRanges(rewritten);
  return escapeOutside(rewritten, ranges2);
}

/** [[start, end), ...] ranges of inline code spans (backtick runs). */
function codeSpanRanges(s) {
  const ranges = [];
  const re = /(`+)[^`]*?\1/g;
  let m;
  while ((m = re.exec(s)) !== null) ranges.push([m.index, m.index + m[0].length]);
  return ranges;
}

function inRanges(pos, ranges) {
  return ranges.some(([a, b]) => pos >= a && pos < b);
}

function escapeOutside(text, ranges) {
  let out = '';
  let cursor = 0;
  const re = /<[A-Za-z][^<>]*>/g;
  let m;
  while ((m = re.exec(text)) !== null) {
    if (inRanges(m.index, ranges)) continue;
    if (/^<[a-z][a-z0-9+.-]*:/i.test(m[0])) continue; // autolink <scheme:...>
    out += text.slice(cursor, m.index) + m[0].replaceAll('<', '&lt;').replaceAll('>', '&gt;');
    cursor = m.index + m[0].length;
  }
  return out + text.slice(cursor);
}

function rewriteLinks(text, fileRel, copySet, ranges) {
  return text.replace(
    /\[([^\]]*)\]\(([^()\s]+)(\s+"[^"]*")?\)/g,
    (full, label, dest, title, offset) => {
      if (inRanges(offset, ranges)) return full; // link syntax itself inside code
      if (/^[a-z][a-z0-9+.-]*:/i.test(dest) || dest.startsWith('//') || dest.startsWith('#'))
        return full;
      const [pathPart, anchor] = splitAnchor(dest);
      if (!pathPart.endsWith('.md')) return full;

      const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(fileRel), pathPart));
      if (copySet.has(resolved)) {
        return `[${label}](${siteUrlFor(resolved)}${anchor ? '#' + anchor : ''}${title ?? ''})`;
      }
      if (!resolved.startsWith('..')) {
        // Inside the spec repo but not copied to the site (e.g. changes/) -> GitHub.
        return `[${label}](${GITHUB_BLOB}${resolved}${anchor ? '#' + anchor : ''}${title ?? ''})`;
      }
      warn(`unresolved link in ${fileRel}: (${dest})`);
      return full;
    },
  );
}

function splitAnchor(dest) {
  const i = dest.indexOf('#');
  if (i === -1) return [dest, ''];
  return [dest.slice(0, i), dest.slice(i + 1)];
}

function ensureFrontmatter(content, title, description) {
  const m = content.match(/^---\n([\s\S]*?)\n---\n?/);
  if (m) {
    let fm = m[1];
    if (!/^title:/m.test(fm)) fm = `title: ${yamlString(title)}\n${fm}`;
    if (description && !/^description:/m.test(fm))
      fm = `${fm}\ndescription: ${yamlString(description)}`;
    return `---\n${fm}\n---\n${content.slice(m[0].length)}`;
  }
  const lines = [`title: ${yamlString(title)}`];
  if (description) lines.push(`description: ${yamlString(description)}`);
  return `---\n${lines.join('\n')}\n---\n${content}`;
}

function injectBanner(frontmattered) {
  const m = frontmattered.match(/^---\n[\s\S]*?\n---\n?/);
  if (!m) return `${BANNER}\n\n${frontmattered}`;
  return `${m[0]}\n${BANNER}\n${frontmattered.slice(m[0].length)}`;
}

function yamlString(s) {
  return JSON.stringify(s);
}

/** frontmatter title -> first H1 -> humanized file name (fumadocs pathToName). */
function extractTitle(content, rel) {
  const fm = content.match(/^---\n([\s\S]*?)\n---/);
  if (fm) {
    const t = fm[1].match(/^title:\s*(.+)$/m);
    if (t) return unquoteYaml(t[1]);
  }
  const h1 = content.match(/^#\s+(.+)$/m);
  if (h1) return stripInlineMarkdown(h1[1]);
  const name = path.posix.basename(rel, '.md');
  const human = name.replaceAll('-', ' ');
  return human.charAt(0).toUpperCase() + human.slice(1);
}

function unquoteYaml(v) {
  v = v.trim();
  if (v.startsWith('"')) {
    try {
      return JSON.parse(v);
    } catch {
      return v.slice(1, -1);
    }
  }
  return v;
}

function stripInlineMarkdown(s) {
  return s
    .replace(/`/g, '')
    .replace(/\*\*/g, '')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .trim();
}

function toOutRel(rel) {
  return rel.replace(/(^|\/)README\.md$/, '$1index.md');
}

/** Root meta.json: Document Map order (skipping uncopied chapters) + "...". */
function renderRootMeta(order, copySet) {
  const pages = [];
  if (order) {
    for (const target of order) {
      if (!copySet.has(target)) continue; // e.g. changes/README.md
      const slug = toOutRel(target).replace(/\.json$/, '').replace(/(^|\/)index$/, '$1');
      const parts = slug.replace(/\.md$/, '').split('/');
      const last = parts[parts.length - 1];
      if (last === 'index' || last === 'README') parts.pop();
      const entry = parts.filter(Boolean).join('/');
      if (entry && !pages.includes(entry)) pages.push(entry);
    }
  }
  pages.push('...');
  return JSON.stringify({ title: 'Language Specification', pages }, null, 2);
}

main().catch((err) => {
  console.error('[spec:sync] failed:', err);
  process.exit(1);
});
